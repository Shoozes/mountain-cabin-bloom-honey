export const CURATED_DRAWINGS = drawings;
export function artRows(size,family,composition=0,weathered=false) {
  const shapes=drawings[size]?.[family]?.[composition];
  if(!shapes)throw Error('Unknown native drawing');
  const rows=Array.from({length:size},()=>Array(size).fill('0'));
  const mark=(x,y,symbol)=>{rows[(y+size)%size][(x+size)%size]=symbol;};
  for(const [i,[x,y,shape]] of shapes.entries()) {
    if(weathered&&i%3===1)continue;
    for(let py=0;py<shape.length;py++)for(let px=0;px<shape[py].length;px++)if(shape[py][px]!=='.')mark(x+px,y+py,weathered&&shape[py][px]==='3'?'2':shape[py][px]);
  }
  // Grass and soil keep quiet seam bands instead of a landmark on every tile.
  // Gravel retains its small shared stone crossing.
  const mid=size/2;
  if(family==='gravel'){mark(size-1,mid-1,'2');mark(0,mid-1,'2');mark(size-1,mid,'1');mark(0,mid,'1');}
  return rows.map(row=>row.join(''));
}
